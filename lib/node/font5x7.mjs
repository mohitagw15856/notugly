/** The glyph for a single character, as a 7-row array of 5 booleans, or a
 * generic filled dot for anything the font doesn't cover — a monogram still
 * needs *something* to draw for '?' or an emoji. */
export function glyphFor(ch) {
  const rows = RAW[String(ch ?? '').toUpperCase()];
  if (rows) return rows.map((row) => [...row].map((c) => c === '#'));
  return ['.....', '.###.', '.###.', '.###.', '.###.', '.....', '.....'].map((row) => [...row].map((c) => c === '#'));
}
